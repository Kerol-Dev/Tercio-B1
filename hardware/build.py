#!/usr/bin/env python3
"""Generate the Tercio B1 KiCad schematic and check it with KiCad itself.

    python3 hardware/build.py            # generate + netlist check + ERC + PDF
    python3 hardware/build.py --no-pdf

Outputs: hardware/kicad/ (the KiCad project, generated — do not edit by hand)
         hardware/build/  (netlist, ERC report, schematic PDF)
"""
from __future__ import annotations

import datetime as dt
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from gen import custom, footprints, sexpr  # noqa: E402
from gen.model import Note, Schematic  # noqa: E402
from gen.sexpr import find, find_all  # noqa: E402
from gen.writer import write  # noqa: E402
from b1 import bridge, driver, mcu, periph, power  # noqa: E402

KICAD_CLI = "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli"
PROJECT = "tercio-b1"


def design() -> Schematic:
    sch = Schematic(PROJECT, "Tercio B1 — brushless FOC driver", "A", "Tercio Labs", "2026-10-12")
    custom.register(sch.lib)
    power.build(sch)
    driver.build(sch)
    bridge.build(sch)
    mcu.build(sch)
    periph.encoder(sch)
    periph.can(sch)
    periph.aux(sch)
    sch.root_notes += [
        Note(30.48, 22.86, "Tercio B1 — brushless FOC driver, rev A", 3.0, True),
        Note(30.48, 30.48, "10–52 V · ~80 A peak design · 15 A continuous target · 46 × 46 mm · STM32G431 + DRV8353RS + MT6835 · "
                           "CAN-FD (Tercio protocol v2, device class 2)", 1.778),
        Note(30.48, 160.02,
             "Conventions\n"
             "• Generated by hardware/gen + hardware/b1 (Python). Do not edit in KiCad: change the code and regenerate.\n"
             "• Power nets use power symbols: VBUS, +5V, +3V3, +3.3VA (filtered analog), GND.\n"
             "• Global labels cross sheets; local labels stay on one sheet.\n"
             "• Reference designators: 1xx power, 2xx driver, 3xx power stage, 4xx MCU, 5xx encoder, 6xx CAN, 7xx aux.\n"
             "• DNP parts (snubbers, phase-voltage taps, I2C pull-ups) are footprints for experiments on rev A.\n"
             "• Planning docs: docs/01–09 (pin map: docs/04-architecture.md; parts: docs/03-parts.md).", 1.524),
    ]
    return sch


def run(args, **kw):
    return subprocess.run([KICAD_CLI] + args, capture_output=True, text=True, **kw)


def check_netlist(sch: Schematic, kdir: pathlib.Path, bdir: pathlib.Path) -> int:
    net_file = bdir / f"{PROJECT}.net"
    r = run(["sch", "export", "netlist", "--format", "kicadsexpr", "-o", str(net_file), str(kdir / f"{PROJECT}.kicad_sch")])
    if r.returncode:
        print(r.stdout, r.stderr)
        return 1
    tree = sexpr.loads(net_file.read_text())
    kicad = {}
    for net in find_all(find(tree, "nets"), "net"):
        nodes = frozenset((find(n, "ref")[1], find(n, "pin")[1]) for n in find_all(net, "node"))
        kicad[nodes] = find(net, "name")[1]
    intended = sch.intended_netlist()
    problems = 0
    for name, nodes in sorted(intended.items()):
        if frozenset(nodes) not in kicad:
            # find the KiCad nets these nodes landed in
            where = {}
            for kn, kname in kicad.items():
                for node in nodes & kn:
                    where.setdefault(kname, []).append(node)
            print(f"  NET MISMATCH {name}: KiCad split/merged it into {where}")
            problems += 1
    matched = {frozenset(n) for n in intended.values()}
    ncs = sch.no_connects()
    for nodes, kname in kicad.items():
        if nodes in matched:
            continue
        if len(nodes) == 1 and next(iter(nodes)) in ncs:
            continue  # an intentional no-connect
        print(f"  UNEXPECTED KiCad net {kname}: {sorted(nodes)}")
        problems += 1
    print(f"netlist: {len(intended)} intended nets all match KiCad's connectivity, "
          f"{len(ncs)} intentional no-connects" if not problems else f"netlist: {problems} problems")
    return problems


def erc(kdir: pathlib.Path, bdir: pathlib.Path) -> int:
    out = bdir / "erc.json"
    run(["sch", "erc", "--format", "json", "--severity-all", "-o", str(out), str(kdir / f"{PROJECT}.kicad_sch")])
    data = json.loads(out.read_text())
    counts: dict[tuple, int] = {}
    shown: dict[tuple, int] = {}
    for sheet in data["sheets"]:
        for v in sheet["violations"]:
            key = (v["severity"], v["type"])
            counts[key] = counts.get(key, 0) + 1
            if shown.get(key, 0) < 4:
                shown[key] = shown.get(key, 0) + 1
                items = "; ".join(i["description"] for i in v["items"])
                print(f"  {v['severity']:7} {v['type']:28} {sheet['path']:10} {items[:150]}")
    total = sum(counts.values())
    print(f"ERC: {total} violations " + ", ".join(f"{k[1]}×{n}" for k, n in sorted(counts.items())))
    return sum(n for k, n in counts.items() if k[0] == "error")


def main():
    kdir, bdir = HERE / "kicad", HERE / "build"
    bdir.mkdir(exist_ok=True)
    sch = design()
    write(sch, kdir)
    footprints.write(kdir)
    parts = sum(1 for s in sch.sheets for p in s.parts if not p.lib_id.startswith("power:"))
    print(f"generated {len(sch.sheets) + 1} sheets, {parts} parts → {kdir}")
    bad = check_netlist(sch, kdir, bdir)
    errors = erc(kdir, bdir)
    if "--no-pdf" not in sys.argv:
        r = run(["sch", "export", "pdf", "-o", str(bdir / f"{PROJECT}-schematic.pdf"), str(kdir / f"{PROJECT}.kicad_sch")])
        print("pdf:", "ok" if r.returncode == 0 else r.stderr[-300:])
    sys.exit(1 if bad or errors else 0)


if __name__ == "__main__":
    main()
